#!/usr/bin/env python3
"""Golden-data generator for the baseline AI kernels.

Writes src/bench_data.h : fixed int8 inputs + the expected outputs computed with NumPy
(all arrays 8-byte aligned; plus the SIMD-friendly layouts used by bench_ai.c: B transposed, the 3x3 weights
 as three zero-padded 64-bit rows, and 8 bytes of zero padding after the image)
(and cross-checked with plain-Python loops, so a NumPy dtype surprise cannot slip through).

Kernel chain (all INT8 in, INT32 accumulate, as in quantised CNN inference):
    dot      : 256-element dot product
    gemm     : C[16x16] = A[16x16] * B[16x16]
    conv3x3  : 16x16 image * 3x3 kernel -> 14x14 (valid, stride 1)
    requant  : (x + 2^(S-1)) >> S, ReLU, clamp to [0,127] -> int8   (applied to the conv output)
    maxpool  : 2x2 max, 14x14 -> 7x7                                 (applied to the requant output)
Usage:  python3 gen_data.py [out_header]   (default: src/bench_data.h)
"""
import sys
import numpy as np

SEED, SHIFT = 2026, 7
DOT_N, M, K, N = 256, 16, 16, 16
IH = IW = 16
OH = OW = IH - 2
PH = PW = OH // 2

rng = np.random.default_rng(SEED)
def i8(*shape): return rng.integers(-128, 128, size=shape, dtype=np.int8)

dot_a, dot_b = i8(DOT_N), i8(DOT_N)
A, B = i8(M, K), i8(K, N)
img, w = i8(IH, IW), i8(3, 3)

# ---- NumPy golden ----
dot_exp = int(np.dot(dot_a.astype(np.int32), dot_b.astype(np.int32)))
C = A.astype(np.int32) @ B.astype(np.int32)
conv = np.zeros((OH, OW), dtype=np.int32)
for ky in range(3):
    for kx in range(3):
        conv += img[ky:ky + OH, kx:kx + OW].astype(np.int32) * np.int32(w[ky, kx])
act = np.clip((conv + (1 << (SHIFT - 1))) >> SHIFT, 0, 127).astype(np.int8)
pool = act.reshape(PH, 2, PW, 2).max(axis=(1, 3))

# ---- independent plain-Python cross-check ----
assert dot_exp == sum(int(x) * int(y) for x, y in zip(dot_a, dot_b))
for i in range(M):
    for j in range(N):
        assert C[i, j] == sum(int(A[i, k]) * int(B[k, j]) for k in range(K))
for y in range(OH):
    for x in range(OW):
        s = sum(int(img[y + a, x + b]) * int(w[a, b]) for a in range(3) for b in range(3))
        assert conv[y, x] == s
        r = max(0, min(127, (s + (1 << (SHIFT - 1))) >> SHIFT))
        assert act[y, x] == r
for y in range(PH):
    for x in range(PW):
        assert pool[y, x] == max(act[2*y, 2*x], act[2*y, 2*x+1], act[2*y+1, 2*x], act[2*y+1, 2*x+1])

def arr(ctype, name, a):
    flat = a.flatten().tolist()
    body = ',\n  '.join(', '.join(str(v) if ctype != 'uint64_t' else '0x%016xULL' % v for v in flat[i:i + 16 if ctype != 'uint64_t' else i + 4]) for i in range(0, len(flat), 16 if ctype != 'uint64_t' else 4))
    return "static const %s %s[%d] __attribute__((aligned(8))) = {\n  %s\n};\n" % (ctype, name, len(flat), body)

# ---- SIMD layouts (same logical data) ----
gemm_bt = np.ascontiguousarray(B.T)                                      # B transposed: rows of BT = columns of B
conv_wp = [sum((int(w[ky, kx]) & 0xFF) << (8 * kx) for kx in range(3)) for ky in range(3)]   # bytes: w[ky][0..2], 0 x5
img_padded = np.concatenate([img.flatten(), np.zeros(8, dtype=np.int8)])  # 8 zero bytes: 64-bit loads may run past the last row

out = sys.argv[1] if len(sys.argv) > 1 else 'src/bench_data.h'
with open(out, 'w') as f:
    f.write("// GENERATED by gen_data.py (seed %d) -- do not edit.\n#ifndef BENCH_DATA_H\n#define BENCH_DATA_H\n#include <stdint.h>\n\n" % SEED)
    for n_, v in (('DOT_N', DOT_N), ('GEMM_M', M), ('GEMM_K', K), ('GEMM_N', N), ('IMG_H', IH), ('IMG_W', IW),
                  ('CONV_OH', OH), ('CONV_OW', OW), ('POOL_H', PH), ('POOL_W', PW), ('REQ_SHIFT', SHIFT)):
        f.write("#define %-9s %d\n" % (n_, v))
    f.write("\n")
    f.write(arr('int8_t', 'dot_a', dot_a) + arr('int8_t', 'dot_b', dot_b))
    f.write("static const int32_t dot_exp = %d;\n\n" % dot_exp)
    f.write(arr('int8_t', 'gemm_a', A) + arr('int8_t', 'gemm_b', B) + arr('int8_t', 'gemm_bt', gemm_bt) + arr('int32_t', 'gemm_exp', C))
    f.write(arr('int8_t', 'conv_img', img_padded) + arr('int8_t', 'conv_w', w) + arr('uint64_t', 'conv_wp', np.array(conv_wp, dtype=object)) + arr('int32_t', 'conv_exp', conv))
    f.write(arr('int8_t', 'req_exp', act) + arr('int8_t', 'pool_exp', pool))
    f.write("\n#endif\n")
print("wrote", out)
print("MACs: dot=%d gemm=%d conv=%d" % (DOT_N, M * N * K, OH * OW * 9))
print("clamped outputs in requant: low=%d high=%d (of %d)" % (
    int(((conv + (1 << (SHIFT - 1))) >> SHIFT <= 0).sum()), int(((conv + (1 << (SHIFT - 1))) >> SHIFT >= 127).sum()), OH * OW))