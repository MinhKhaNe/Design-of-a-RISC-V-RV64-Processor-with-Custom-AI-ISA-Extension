`timescale 1ns/1ps

module tb_pipeline;

    logic clk;
    logic rst_n;

    // =========================================================
    // DUT
    // =========================================================

    rv64im_top #(
        .RESET_PC(64'h0),
        .TRAP_PC (64'h000004e0)
    ) dut (
        .clk             (clk),
        .rst_n           (rst_n),
        .pc_o            (),
        .stall_o         (),
        .flush_o         (),
        .illegal_instr_o ()
    );

    // =========================================================
    // CLOCK
    // =========================================================

    initial begin
        clk = 1'b0;
        forever #5 clk = ~clk;
    end

    // =========================================================
    // RESET
    // =========================================================

    initial begin
        rst_n = 1'b0;

        #20;

        rst_n = 1'b1;
    end

    // =========================================================
    // PIPELINE TRACE
    // =========================================================

    initial begin

        $display("");
        $display("==============================================================================================================");
        $display(" TIME |       IF STAGE        |    ID STAGE    |       EX STAGE        |       MEM STAGE       |   WB STAGE");
        $display("      | PC         INST       | PC             | PC         ALU_RESULT | ALU_RESULT  MEM_DATA | WRITE_DATA");
        $display("==============================================================================================================");

        wait(rst_n);

        forever begin
            @(posedge clk);
            #1;

            $display(
                "%6t | %08h  %08h | %08h       | %08h  %016h | %016h  %016h | %016h",
                
                $time,

                // -------------------------------------------------
                // IF
                // -------------------------------------------------
                dut.pc,
                dut.if_instr,

                // -------------------------------------------------
                // ID
                // -------------------------------------------------
                dut.ifid_pc,

                // -------------------------------------------------
                // EX
                // -------------------------------------------------
                dut.idex_pc,
                dut.ex_alu_result,

                // -------------------------------------------------
                // MEM
                // -------------------------------------------------
                dut.exmem_alu_result,
                dut.mem_rdata,

                // -------------------------------------------------
                // WB
                // -------------------------------------------------
                dut.wb_data
            );
        end
    end

    // =========================================================
    // STOP
    // =========================================================

    initial begin
        #3000;

        $display("");
        $display("============================================================");
        $display(" SIMULATION FINISHED");
        $display("============================================================");

        $finish;
    end

endmodule